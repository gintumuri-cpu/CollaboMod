package com.COLLABOMOD.collabomod.magic;

public enum EnumMagicAnimation {
    EXPAND_FADE,    // 爆発：急激に広がり、徐々に消える
    CONVERGE,       // 収束：外側から中心に集まる（重力魔法など）
    SUSTAIN_SPIN,   // 維持：一定サイズで回転し続ける（シールド・設置型）
    PULSE,          // 脈動：大きくなったり小さくなったり（生物的・不安定）
    RISE,           // 上昇：下から上へ吹き上がる（円柱・竜巻）
    SHOOT_AHEAD,     // 射出：術者の前方へ伸びる（ビーム・衝撃波）
    IMPLODE,
    BEAM_EXTEND,
    FIXED,

}